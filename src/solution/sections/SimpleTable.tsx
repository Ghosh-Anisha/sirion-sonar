import "./Sections.css";

/** A plain table from columns and rows of text, for the architecture sections. The first column is a row header. */
export function SimpleTable({ caption, columns, rows, tour }: { caption: string; columns: string[]; rows: string[][]; tour?: string }) {
  return (
    <div className="table-wrap" data-tour={tour}>
      <table className="table">
        <caption className="visually-hidden">{caption}</caption>
        <thead>
          <tr>
            {columns.map((c) => (
              <th key={c} scope="col">
                {c}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r[0]}>
              {r.map((cell, i) =>
                i === 0 ? (
                  <th key={i} scope="row">
                    {cell}
                  </th>
                ) : (
                  <td key={i}>{cell}</td>
                ),
              )}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
